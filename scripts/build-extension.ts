/**
 * Generate extension/recorder.js — the in-page recorder for the Chrome
 * extension — from the SAME strings the Playwright recorder injects, so the
 * two can't drift apart.
 *
 *   npm run extension:build
 *
 * Committed, so the extension can be loaded unpacked without building.
 * test/extension.test.ts fails if it's out of date.
 */

import { writeFile } from 'node:fs/promises';
import { ACCNAME_BUNDLE } from '../src/adapters/recorder/accname-bundle.js';
import { INJECTED_LISTENER } from '../src/adapters/recorder/injected.js';

export function recorderSource(): string {
  return [
    '// GENERATED by scripts/build-extension.ts — do not edit. Run: npm run extension:build',
    '// The accessible-name library, a bridge to the extension, then the recorder.',
    ACCNAME_BUNDLE,
    // The recorder hands every action to window.__understudyEmit; in the
    // Playwright recorder that's a binding, here it's a message to background.js.
    `window.__understudyEmit = function (event) {
  try { chrome.runtime.sendMessage({ type: 'understudy:event', event: event }); } catch (e) { /* extension reloaded */ }
};`,
    INJECTED_LISTENER,
    '',
  ].join('\n');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  await writeFile(new URL('../extension/recorder.js', import.meta.url), recorderSource());
  console.log('wrote extension/recorder.js');
}
